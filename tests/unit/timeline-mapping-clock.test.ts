import { readFileSync } from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";

import { activeGroups } from "@/analysis/extract";
import { createMappingState, decideStep, euclidHit, scaleNote, DEFAULT_LAYERS } from "@/audio/mapping";
import { FeatureFrameSchema, type FeatureFrame } from "@/contracts/frame";
import { FeatureTimeline } from "@/data/feature-timeline";
import { PlaybackClock } from "@/playback/clock";
import { getSource } from "@/registry/sources";
import { phaseAt } from "@/registry/timeline";

/** Real image-derived features of NASA SVS 5313 (generated by tests/calibration/media.calibration.ts). */
const fixture: FeatureFrame[] = JSON.parse(readFileSync(path.resolve(__dirname, "../fixtures/svs5313-features.json"), "utf8"));
const nl = getSource("svs-5313")!;

describe("source-derived fixture", () => {
  it("validates against the internal contract", () => {
    expect(fixture.length).toBeGreaterThan(80);
    for (const f of fixture) expect(FeatureFrameSchema.safeParse(f).success).toBe(true);
  });
});

describe("FeatureTimeline", () => {
  it("orders out-of-order arrivals and rejects duplicates, stale generations and other sources", () => {
    const tl = new FeatureTimeline();
    const gen = tl.reset("svs-5313", "svs5313-nightlights-eic");
    const shuffled = [...fixture.slice(0, 20)].reverse();
    for (const f of shuffled) expect(tl.insert(f, gen)).toBe("inserted");
    expect(tl.stats.outOfOrder).toBeGreaterThan(0);
    const times = tl.all().map((f) => f.presentationTimeS);
    expect(times).toEqual([...times].sort((a, b) => a - b));
    expect(tl.insert(fixture[3], gen)).toBe("duplicate");
    expect(tl.insert(fixture[30], gen - 1)).toBe("stale");
    expect(tl.insert({ ...fixture[31], sourceId: "svs-3912" }, gen)).toBe("wrong-source");
    expect(tl.size).toBe(20);
  });

  it("returns null (missing) when the nearest frame is too old", () => {
    const tl = new FeatureTimeline();
    const gen = tl.reset("svs-5313", "svs5313-nightlights-eic");
    tl.insert(fixture[0], gen); // t = 0
    tl.insert(fixture[10], gen); // t = 5
    expect(tl.at(0.4, 0.6)?.frameId).toBe(fixture[0].frameId);
    expect(tl.at(2.5, 0.6)).toBeNull(); // gap: no invented value
    expect(tl.at(5.2, 0.6)?.frameId).toBe(fixture[10].frameId);
  });

  it("stays bounded", () => {
    const tl = new FeatureTimeline(10);
    const gen = tl.reset("svs-5313", "svs5313-nightlights-eic");
    for (const f of fixture) tl.insert(f, gen);
    expect(tl.size).toBe(10);
    expect(tl.stats.evicted).toBe(fixture.length - 10);
  });
});

describe("deterministic sonification mapping", () => {
  const profile = nl.sonification!;
  const run = () => {
    const state = createMappingState();
    return fixture.map((frame, i) =>
      decideStep({ frame, profile, groups: activeGroups(nl.analysis!, phaseAt(nl, frame.presentationTimeS)?.id ?? null), stepIndex: i, state, layers: DEFAULT_LAYERS }),
    );
  };

  it("produces identical decisions for identical input", () => {
    expect(run()).toEqual(run());
  });

  it("stays within bounds and respects polyphony limits", () => {
    for (const d of run()) {
      expect(d.padGain).toBeGreaterThanOrEqual(0);
      expect(d.padGain).toBeLessThanOrEqual(1);
      expect(d.notes.length).toBeLessThanOrEqual(profile.maxVoicesPerStep);
      for (const n of d.notes) {
        expect(n.velocity).toBeGreaterThan(0);
        expect(n.velocity).toBeLessThanOrEqual(1);
        expect(n.midi).toBeGreaterThanOrEqual(profile.rootMidi);
        expect(n.midi).toBeLessThanOrEqual(profile.rootMidi + 24 + 12 * profile.octaves);
      }
    }
  });

  it("uses change-phase voices only in change phases of the real asset", () => {
    const decisions = run();
    const changeNotes = decisions.filter((d, i) => phaseAt(nl, fixture[i].presentationTimeS)?.id.startsWith("change")).flatMap((d) => d.notes);
    const annualNotes = decisions.filter((d, i) => phaseAt(nl, fixture[i].presentationTimeS)?.id.startsWith("annual")).flatMap((d) => d.notes);
    expect(changeNotes.length).toBeGreaterThan(0);
    expect(annualNotes.length).toBeGreaterThan(0);
    expect(new Set(changeNotes.map((n) => n.groupId))).not.toContain("lights");
    expect(new Set(annualNotes.map((n) => n.groupId))).toEqual(new Set(["lights"]));
  });

  it("is silent for missing data and when layers are off", () => {
    const state = createMappingState();
    const missing = decideStep({ frame: null, profile, groups: [], stepIndex: 0, state, layers: DEFAULT_LAYERS });
    expect(missing.frameMissing).toBe(true);
    expect(missing.notes).toEqual([]);
    expect(missing.padGain).toBe(0);
    const off = decideStep({
      frame: fixture[5],
      profile,
      groups: activeGroups(nl.analysis!, "annual-global"),
      stepIndex: 0,
      state: createMappingState(),
      layers: { pad: false, pulse: false, groups: { lights: false } },
    });
    expect(off.padGain).toBe(0);
    expect(off.notes).toEqual([]);
    expect(off.pulse).toBeNull();
  });

  it("has exact Euclidean rhythms and scale mapping", () => {
    const hits = (k: number) => Array.from({ length: 8 }, (_, i) => euclidHit(k, 8, i)).filter(Boolean).length;
    expect([0, 1, 3, 5, 8].map(hits)).toEqual([0, 1, 3, 5, 8]);
    expect(scaleNote(profile, 0)).toBe(profile.rootMidi);
    expect(scaleNote(profile, 1)).toBe(profile.rootMidi + 12 + 9);
  });
});

describe("PlaybackClock (master clock)", () => {
  it("advances with the audio clock, pauses, seeks and changes rate without jumps", () => {
    let now = 100;
    const c = new PlaybackClock(() => now);
    c.start(2);
    now = 101;
    expect(c.now()).toBeCloseTo(3);
    c.setRate(2);
    now = 102;
    expect(c.now()).toBeCloseTo(5);
    expect(c.audioTimeFor(6)).toBeCloseTo(102.5);
    c.pause();
    now = 110;
    expect(c.now()).toBeCloseTo(5);
    c.seek(1);
    expect(c.now()).toBeCloseTo(1);
  });

  it("re-anchors to observed video frames only beyond the drift threshold", () => {
    let now = 0;
    const c = new PlaybackClock(() => now);
    c.start(0);
    now = 1;
    expect(c.discipline(0.97, 1, 0.06)).toEqual({ driftS: expect.closeTo(0.03, 6), corrected: false });
    const r = c.discipline(0.8, 1, 0.06);
    expect(r.corrected).toBe(true);
    expect(c.presentationAt(1)).toBeCloseTo(0.8);
  });
});
